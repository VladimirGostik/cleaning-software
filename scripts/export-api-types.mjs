import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'resources/js/types/generated.d.ts');
const defaultTarget = resolve(root, '../cleaning-software-app/src/types/api.generated.d.ts');
const target = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : defaultTarget;
const header = '// generated by cleaning-software: pnpm api-types:export — do not edit\n';

if (!process.argv[2] && !existsSync(resolve(root, '../cleaning-software-app'))) {
    console.error('Mobile checkout not found at ../cleaning-software-app. Create it first or pass a target path.');
    process.exit(1);
}

mkdirSync(dirname(target), { recursive: true });
copyFileSync(source, target);
writeFileSync(target, header + readFileSync(target, 'utf8'));
console.log(`Exported ${source} -> ${target}`);
